// Requires Node 22.18+ for loading the existing TypeScript data and text decoder.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const {decodeGBAString} = require('../src/exporter/charmap.ts');
const {SPECIES, MOVES, ITEMS} = require('../src/exporter/run-and-bun/data.ts');

const expectedHash = '68ec5b0c02e6def8da8dc2b1857b269505418803d44cc2b816fb7471587bf89d';
const filename = process.argv[2];
if (!filename) throw new Error('Usage: node scripts/generate-run-and-bun-tables.cjs <reference.gba>');
const rom = fs.readFileSync(filename);
const hash = crypto.createHash('sha256').update(rom).digest('hex');
if (hash !== expectedHash) throw new Error(`Unsupported reference ROM SHA-256: ${hash}`);

const abilities = Array.from({length: 268}, (_, id) => {
  const name = id === 0 ? 'None' : decodeGBAString(rom.subarray(0x3AC0C9 + id * 17, 0x3AC0C9 + (id + 1) * 17), 17);
  if (!name || name.includes('?')) throw new Error(`Invalid ability name for ID ${id}`);
  return name;
});
const species = Array.from({length: SPECIES.length + 1}, (_, id) => {
  const offset = 0x3B7CE0 + id * 36;
  return [
    ...rom.subarray(offset, offset + 6), rom[offset + 21],
    ...Array.from({length: 3}, (_, slot) => rom.readUInt16LE(offset + 24 + slot * 2)),
  ];
});
const movePp = MOVES.map((_, id) => rom[0x3B0C5C + id * 20 + 6]);
const itemPockets = Array.from({length: ITEMS.length + 1}, (_, id) => rom[0x678D60 + id * 44 + 26]);
const experience = Array.from({length: 6}, (_, growth) =>
  Array.from({length: 101}, (_, level) => rom.readUInt32LE(0x3B7040 + growth * 404 + level * 4)));
const rows = values => values.map(value => `  ${JSON.stringify(value)},`).join('\n');
const numbers = values => Array.from({length: Math.ceil(values.length / 24)}, (_, index) =>
  `  ${values.slice(index * 24, (index + 1) * 24).join(', ')},`).join('\n');
const output = `// Generated by scripts/generate-run-and-bun-tables.cjs. Only decoder lookup data, not ROM code/assets.
// Species rows: HP, Atk, Def, Spe, SpA, SpD, growth group, ability slots 0/1/2. IDs index rows directly.
export const REFERENCE_ROM_SHA256 = '${hash}';

export const ABILITY_NAMES: readonly string[] = [
${rows(abilities)}
];

export const SPECIES_INFO: readonly (readonly number[])[] = [
${rows(species)}
];

export const MOVE_PP: readonly number[] = [
${numbers(movePp)}
];

export const ITEM_POCKETS: readonly number[] = [
${numbers(itemPockets)}
];

export const EXPERIENCE: readonly (readonly number[])[] = [
${rows(experience)}
];
`;
const destination = path.join(__dirname, '..', 'src', 'exporter', 'run-and-bun', 'tables.ts');
fs.writeFileSync(destination, output);
console.log(`Wrote ${Buffer.byteLength(output).toLocaleString()} bytes of lookup tables.`);
